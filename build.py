#!/usr/bin/env python3
"""Bakes the page content into index.html so search engines and link-preview bots see it without running scripts.

The visible page is unchanged: the script in the page still builds everything from content.js and replaces the baked HTML.

Workflow
  * edit content.js (texts, prices, reviews, FAQ ...) or index.template.html (page markup) - never index.html directly
  * run:  python3 build.py        (needs Google Chrome installed; it renders the page in a hidden window)
  * upload index.html (and the other changed files) to GitHub; index.template.html and build.py do not need uploading
"""
import functools, http.server, json, os, re, socketserver, subprocess, sys, threading
from html import unescape

ROOT = os.path.dirname(os.path.abspath(__file__))
TEMPLATE, OUT = "index.template.html", "index.html"
IDS = ["hero-lead", "steps", "services", "where", "about-title", "team", "reviews", "gallery", "faq-list", "c-phone", "c-mail"]
CHROMES = ["/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
           "/Applications/Chromium.app/Contents/MacOS/Chromium",
           "/usr/bin/google-chrome", "/usr/bin/chromium", "/usr/bin/chromium-browser"]


def render():
    chrome = next((c for c in CHROMES if os.path.exists(c)), None)
    if not chrome:
        sys.exit("Google Chrome not found - install it or add its path to CHROMES in build.py")

    class Quiet(http.server.SimpleHTTPRequestHandler):
        def log_message(self, *a):
            pass

    handler = functools.partial(Quiet, directory=ROOT)
    with socketserver.TCPServer(("127.0.0.1", 0), handler) as srv:
        threading.Thread(target=srv.serve_forever, daemon=True).start()
        url = "http://127.0.0.1:%d/%s?bake=1" % (srv.server_address[1], TEMPLATE)
        r = subprocess.run([chrome, "--headless=new", "--disable-gpu", "--virtual-time-budget=8000", "--dump-dom", url],
                           capture_output=True, text=True, timeout=120)
        srv.shutdown()
    if "id=\"services\"" not in r.stdout:
        sys.exit("Chrome returned no page - is index.template.html valid?")
    return r.stdout


def span(html, el_id):
    """(inner_start, inner_end) of the element with this id, matching nested tags of the same name."""
    m = re.search(r'<(\w+)\b[^>]*\bid="%s"[^>]*>' % re.escape(el_id), html)
    if not m:
        return None
    tag, depth, pos = m.group(1), 1, m.end()
    for t in re.finditer(r'<(/?)%s\b[^>]*>' % tag, html[pos:]):
        depth += -1 if t.group(1) else 1
        if depth == 0:
            return pos, pos + t.start()
    return None


def clean(fragment):
    # the "in" class marks elements already revealed by scrolling; baked elements start hidden like the live ones
    def classes(m):
        keep = [c for c in m.group(1).split() if c != "in"]
        return 'class="%s"' % " ".join(keep) if keep else ""
    return re.sub(r'class="([^"]*)"', classes, fragment)


def main():
    dump = render()
    html = open(os.path.join(ROOT, TEMPLATE), encoding="utf-8").read()
    for el_id in IDS:
        s = span(dump, el_id)
        if not s:
            sys.exit("missing in rendered page: " + el_id)
        inner = clean(dump[s[0]:s[1]])
        if el_id == "reviews":   # keep the real cards, drop the carousel's hidden duplicates
            parts = re.split(r'(?=<figure )', inner)
            inner = "".join(p for p in parts if not re.match(r'<figure[^>]*aria-hidden="true"', p))
        t = span(html, el_id)
        if not t:
            sys.exit("missing in template: " + el_id)
        html = html[:t[0]] + inner + html[t[1]:]
    label = re.search(r'<h1 id="hero-title" aria-label="([^"]*)"', dump)
    t = span(html, "hero-title")
    if label and t:
        html = html[:t[0]] + '<span class="seo-text">%s</span>' % label.group(1) + html[t[1]:]
    # FAQPage structured data, generated from the rendered FAQ so it always matches the visible answers
    faq = []
    s = span(dump, "faq-list")
    if s:
        for item in re.findall(r'<span class="faq-t">(.*?)</span>.*?<div class="faq-a"><div><p>(.*?)</p>', dump[s[0]:s[1]], re.S):
            faq.append({"@type": "Question", "name": unescape(item[0]),
                        "acceptedAnswer": {"@type": "Answer", "text": unescape(re.sub(r"<[^>]+>", "", item[1]))}})
    block = ""
    if faq:
        block = '<script type="application/ld+json">\n' + json.dumps({"@context": "https://schema.org", "@type": "FAQPage", "mainEntity": faq}, ensure_ascii=False, indent=1) + "\n</script>"
    html = html.replace("<!-- FAQ-JSONLD -->", block)
    html = html.replace("<!doctype html>", "<!doctype html>\n<!-- generated by build.py from index.template.html + content.js: edit those, not this file -->", 1)
    open(os.path.join(ROOT, OUT), "w", encoding="utf-8").write(html)
    print("wrote %s (%d KB)" % (OUT, len(html) // 1024))


if __name__ == "__main__":
    main()
